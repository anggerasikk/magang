        // Fungsi pencarian
        document.querySelector('.search-form').addEventListener('submit', function(e) {
            e.preventDefault();
            const keyword = this.querySelector('input[type="text"]').value;
            
            if (!keyword.trim()) {
                alert('Masukkan kata kunci pencarian!');
                return;
            }
            
            alert(`Mencari naskah akademik dengan kata kunci: "${keyword}"\n\nHasil pencarian akan ditampilkan di bawah.`);
        });
        
        // Fungsi filter tahun
        document.querySelectorAll('.year-btn').forEach(btn => {
            btn.addEventListener('click', function(e) {
                e.preventDefault();
                // Remove active class from all buttons
                document.querySelectorAll('.year-btn').forEach(b => {
                    b.classList.remove('active');
                });
                // Add active class to clicked button
                this.classList.add('active');
                
                const year = this.textContent;
                alert(`Memfilter naskah akademik tahun: ${year}\n\nFungsi filter akan bekerja dengan request AJAX ke server.`);
            });
        });
        
        // Fungsi filter institusi
        document.querySelectorAll('.list-group-item').forEach(item => {
            item.addEventListener('click', function(e) {
                e.preventDefault();
                const institusi = this.textContent.split(' ')[0];
                const count = this.querySelector('.badge').textContent;
                
                alert(`Memfilter berdasarkan institusi: ${institusi}\n\nJumlah naskah: ${count} dokumen\n\nFungsi filter akan bekerja dengan request AJAX ke server.`);
            });
        });
        
        // Fungsi download
        document.querySelectorAll('.btn-download').forEach(btn => {
            btn.addEventListener('click', function(e) {
                e.preventDefault();
                const docTitle = this.closest('.document-card').querySelector('.card-title a').textContent;
                
                alert(`Mengunduh naskah akademik: "${docTitle}"\n\nDokumen akan mulai diunduh dalam beberapa detik.`);
                
                // Simulasi download
                setTimeout(() => {
                    alert('Download berhasil!');
                }, 1000);
            });
        });
        
        // Fungsi preview
        document.querySelectorAll('.btn-view').forEach(btn => {
            btn.addEventListener('click', function(e) {
                e.preventDefault();
                const docTitle = this.closest('.document-card').querySelector('.card-title a').textContent;
                
                if (this.querySelector('.bi-link-45deg')) {
                    alert(`Mengarahkan ke Raperda terkait naskah akademik: "${docTitle}"\n\nDalam implementasi real, akan membuka halaman Raperda.`);
                } else {
                    alert(`Membuka preview naskah akademik: "${docTitle}"\n\nPreview akan dibuka di tab baru.`);
                }
            });
        });
        
        // Accordion functionality
        document.querySelectorAll('.accordion-button').forEach(button => {
            button.addEventListener('click', function() {
                const icon = this.querySelector('i');
                if (this.classList.contains('collapsed')) {
                    icon.className = 'bi bi-chevron-down me-2';
                } else {
                    icon.className = 'bi bi-chevron-up me-2';
                }
            });
        });
        
